"""aran_cloud/db.py: the storage layer of Aran Cloud.

SQLite is the default (a file, ARAN_CLOUD_DB). Set ARAN_CLOUD_DATABASE_URL=postgresql://... to use Postgres instead.
The Cloud code is written in the SQLite dialect. For Postgres a thin adapter translates each statement
(placeholders, INSERT OR IGNORE / OR REPLACE, AUTOINCREMENT, PRAGMA, lastrowid) and returns rows that behave like
sqlite3.Row (index and name access, dict(row)). psycopg is an optional import: SQLite needs nothing extra.
"""

import os
import re
import sqlite3
import threading
import time
from queue import Empty, LifoQueue
from typing import Optional

try:
    import psycopg
    from psycopg.adapt import Loader
    HAVE_PSYCOPG = True
except ImportError:      # optional: only needed for a Postgres URL
    psycopg = None
    Loader = object
    HAVE_PSYCOPG = False

# what the Cloud code catches (SQLite and Postgres raise different classes)
IntegrityError = (sqlite3.IntegrityError,) + ((psycopg.errors.IntegrityError,) if HAVE_PSYCOPG else ())


def is_postgres(url: Optional[str]) -> bool:
    return bool(url) and url.split(":", 1)[0] in ("postgres", "postgresql")


# ---------------------------------------------------------------- SQL translation (SQLite dialect -> Postgres)
_STR = re.compile(r"'(?:[^']|'')*'")


def _outside_strings(sql: str, fn) -> str:
    """Applies fn to the parts of the statement that are not quoted strings."""
    out, last = [], 0
    for m in _STR.finditer(sql):
        out.append(fn(sql[last:m.start()]))
        out.append(m.group(0).replace("%", "%%"))
        last = m.end()
    out.append(fn(sql[last:]))
    return "".join(out)


def _placeholders(part: str) -> str:
    return part.replace("%", "%%").replace("?", "%s")


_STRFTIME_DAY = re.compile(r"strftime\(\s*'%Y-%m-%d'\s*,\s*(\w+)\s*\+\s*(\d+)\s*,\s*'unixepoch'\s*\)", re.I)
_INSERT_OR = re.compile(r"^\s*INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\s+(\w+)\s*(\(([^)]*)\))?", re.I)
_PRAGMA_TABLE = re.compile(r"^\s*PRAGMA\s+table_info\(\s*(\w+)\s*\)\s*;?\s*$", re.I)
_ALTER_ADD = re.compile(r"^(\s*ALTER\s+TABLE\s+\w+\s+ADD\s+COLUMN\s+)(?!IF NOT EXISTS)", re.I)
_INSERT_INTO = re.compile(r"^\s*INSERT\s+INTO\s+(\w+)", re.I)


def translate(sql: str, pk_of=lambda table: []) -> tuple:
    """Returns (postgres_sql, kind). kind is '', 'skip' (nothing to run), 'columns:<table>' (PRAGMA table_info),
    'lock' or 'insert:<table>' (an INSERT that may need RETURNING id)."""
    s = sql.strip().rstrip(";").strip()
    head = s.upper()
    if head.startswith("PRAGMA"):
        m = _PRAGMA_TABLE.match(sql)
        return ("", "columns:" + m.group(1)) if m else ("", "skip")
    if head in ("BEGIN IMMEDIATE", "BEGIN EXCLUSIVE", "BEGIN"):
        # SQLite takes the write lock here. Postgres: an advisory lock held to the end of the transaction.
        return "SELECT pg_advisory_xact_lock(7101)", "lock"
    kind = ""
    if head.startswith("CREATE") or head.startswith("ALTER"):
        s = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s, flags=re.I)
        s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s, flags=re.I)   # Postgres REAL is 4 bytes: too short for a timestamp
        s = _ALTER_ADD.sub(r"\1IF NOT EXISTS ", s)
    m = _INSERT_OR.match(s)
    if m:
        mode, table, cols = m.group(1).upper(), m.group(2), m.group(4)
        s = _INSERT_OR.sub(lambda x: f"INSERT INTO {x.group(2)} " + (f"({x.group(4)})" if x.group(4) else ""), s, count=1)
        if mode == "IGNORE":
            s += " ON CONFLICT DO NOTHING"
        else:
            keys = pk_of(table)
            names = [c.strip() for c in (cols or "").split(",") if c.strip()]
            sets = [f"{c}=EXCLUDED.{c}" for c in names if c not in keys]
            s += f" ON CONFLICT ({', '.join(keys)}) " + (f"DO UPDATE SET {', '.join(sets)}" if sets else "DO NOTHING")
    else:
        m2 = _INSERT_INTO.match(s)
        if m2 and "ON CONFLICT" not in s.upper():
            kind = "insert:" + m2.group(1)
    s = _STRFTIME_DAY.sub(lambda x: f"to_char(to_timestamp({x.group(1)} + {x.group(2)}) AT TIME ZONE 'UTC', 'YYYY-MM-DD')", s)
    return _outside_strings(s, _placeholders), kind


# ---------------------------------------------------------------- rows
class Row:
    """Like sqlite3.Row: r[0], r["name"], r.keys(), dict(r), iteration over values."""
    __slots__ = ("_keys", "_vals")

    def __init__(self, keys, vals):
        self._keys = keys
        self._vals = vals

    def __getitem__(self, k):
        if isinstance(k, (int, slice)):
            return self._vals[k]
        try:
            return self._vals[self._keys.index(k)]
        except ValueError:
            raise IndexError(f"No item with that key: {k}")

    def keys(self):
        return list(self._keys)

    def __iter__(self):
        return iter(self._vals)

    def __len__(self):
        return len(self._vals)

    def __eq__(self, other):
        return tuple(self._vals) == tuple(other)

    __hash__ = None

    def __repr__(self):
        return f"Row({dict(zip(self._keys, self._vals))})"


def _row_factory(cursor):
    keys = [c.name for c in (cursor.description or [])]
    return lambda vals: Row(keys, tuple(vals))


if HAVE_PSYCOPG:
    class _NumLoader(Loader):
        """SUM() of an integer column is numeric in Postgres; hand back int (or float) like SQLite does."""
        def load(self, data):
            t = bytes(data).decode()
            if t in ("NaN", "Infinity", "-Infinity"):
                return float(t)
            return int(t) if re.fullmatch(r"-?\d+", t) else float(t)


class _Cursor:
    def __init__(self, cur, lastrowid=None, rows=None):
        self._cur = cur
        self.lastrowid = lastrowid
        self._rows = rows           # set for emulated results (PRAGMA)

    @property
    def rowcount(self):
        return self._cur.rowcount if self._cur is not None else -1

    def fetchone(self):
        if self._rows is not None:
            return self._rows.pop(0) if self._rows else None
        return self._cur.fetchone() if self._cur is not None and self._cur.description else None

    def fetchall(self):
        if self._rows is not None:
            r, self._rows = self._rows, []
            return r
        return self._cur.fetchall() if self._cur is not None and self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


class PgConn:
    """The part of sqlite3.Connection that the Cloud code uses, on a psycopg connection."""

    def __init__(self, raw, pool=None):
        self._raw = raw
        self._pool = pool
        self._meta = _META

    # sqlite3 compatibility
    row_factory = None

    @property
    def in_transaction(self) -> bool:
        return self._raw.info.transaction_status != psycopg.pq.TransactionStatus.IDLE

    def _pk(self, table):
        key = ("pk", table)
        if key not in self._meta:
            rows = self._raw.execute(
                """SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
                   WHERE i.indrelid = %s::regclass AND i.indisprimary ORDER BY a.attnum""", (table,)).fetchall()
            self._meta[key] = [r[0] for r in rows]
        return self._meta[key]

    def _table_exists(self, table):
        return bool(self._raw.execute("SELECT to_regclass(%s)", (table,)).fetchone()[0])

    def _has_identity_id(self, table):
        key = ("id", table)
        if key not in self._meta:
            r = self._raw.execute(
                "SELECT 1 FROM information_schema.columns WHERE table_name = %s AND column_name = 'id' AND is_identity = 'YES' "
                "AND table_schema = current_schema()", (table,)).fetchone()
            self._meta[key] = bool(r)
        return self._meta[key]

    def execute(self, sql, params=()):
        pg, kind = translate(sql, pk_of=self._pk)
        if kind == "skip":
            return _Cursor(None, rows=[])
        if kind.startswith("columns:"):
            table = kind[8:]
            pks = self._pk(table) if self._table_exists(table) else []
            cur = self._raw.execute(
                "SELECT ordinal_position - 1, column_name, data_type, CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END, column_default "
                "FROM information_schema.columns WHERE table_name = %s AND table_schema = current_schema() ORDER BY ordinal_position",
                (table,))
            names = ["cid", "name", "type", "notnull", "dflt_value", "pk"]
            rows = [Row(names, (*r, (pks.index(r[1]) + 1) if r[1] in pks else 0)) for r in cur.fetchall()]
            return _Cursor(None, rows=rows)
        returning = False
        if kind.startswith("insert:") and self._has_identity_id(kind[7:]):
            pg += " RETURNING id"
            returning = True
        cur = self._raw.cursor(row_factory=_row_factory)
        cur.execute(pg, tuple(params))
        if returning:
            row = cur.fetchone()
            return _Cursor(cur, lastrowid=row[0] if row else None, rows=[])
        return _Cursor(cur)

    def executemany(self, sql, seq):
        for params in seq:
            self.execute(sql, params)

    def iterdump(self):
        """Every table's rows as text lines (the tests use it to prove no raw value is stored)."""
        names = [r[0] for r in self._raw.execute("SELECT tablename FROM pg_tables WHERE schemaname = current_schema()").fetchall()]
        for t in names:
            cur = self._raw.execute(f'SELECT * FROM "{t}"')
            for row in cur.fetchall():
                yield f"INSERT INTO {t} VALUES {tuple(row)!r};"

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def __enter__(self):
        return self

    def __exit__(self, et, ev, tb):
        if et is None:
            self._raw.commit()
        else:
            self._raw.rollback()
        return False

    def close(self):
        """Hands the connection back to the pool (an open transaction is rolled back, as sqlite3 does on close)."""
        try:
            self._raw.rollback()
        except Exception:
            self._raw.close()
            return
        if self._pool is not None and not self._raw.closed:
            try:
                self._pool.put_nowait(self._raw)
                return
            except Exception:
                pass
        self._raw.close()


_META = {}      # catalog facts (primary keys, identity columns) shared by all connections
_pools = {}
_pool_lock = threading.Lock()
POOL_SIZE = int(os.environ.get("ARAN_CLOUD_DB_POOL", "10"))


def _pg_connect(url: str) -> PgConn:
    if not HAVE_PSYCOPG:
        raise RuntimeError("ARAN_CLOUD_DATABASE_URL is a Postgres URL but psycopg is not installed: pip install 'psycopg[binary]'")
    with _pool_lock:
        pool = _pools.setdefault(url, LifoQueue(POOL_SIZE))
    raw = None
    while raw is None:
        try:
            raw = pool.get_nowait()
        except Empty:
            break
        if raw.closed:
            raw = None
    if raw is None:
        raw = psycopg.connect(url, autocommit=False)
        raw.adapters.register_loader("numeric", _NumLoader)
    return PgConn(raw, pool)


def connect(sqlite_path: str, url: Optional[str] = None):
    """A connection with dict-like rows. url (ARAN_CLOUD_DATABASE_URL) picks Postgres, else the SQLite file."""
    if is_postgres(url):
        return _pg_connect(url)
    conn = sqlite3.connect(sqlite_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL;")
    return conn


# ---------------------------------------------------------------- leases for background sweepers
def init_leases(conn):
    conn.execute("CREATE TABLE IF NOT EXISTS leases (name TEXT PRIMARY KEY, holder TEXT NOT NULL, until REAL NOT NULL)")


def acquire_lease(conn, name: str, holder: str, ttl: float, now: Optional[float] = None) -> bool:
    """True when `holder` now holds the lease `name`: it was free, expired, or already this holder's (renewed).
    One statement, so two instances can never both win."""
    now = time.time() if now is None else now
    with conn:
        conn.execute(
            "INSERT INTO leases (name, holder, until) VALUES (?, ?, ?) "
            "ON CONFLICT (name) DO UPDATE SET holder = excluded.holder, until = excluded.until "
            "WHERE leases.until < ? OR leases.holder = excluded.holder",
            (name, holder, now + ttl, now))
    row = conn.execute("SELECT holder FROM leases WHERE name = ?", (name,)).fetchone()
    return bool(row) and row["holder"] == holder


def release_lease(conn, name: str, holder: str):
    with conn:
        conn.execute("DELETE FROM leases WHERE name = ? AND holder = ?", (name, holder))
