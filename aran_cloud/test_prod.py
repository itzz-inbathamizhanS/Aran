def test_lease_is_exclusive_until_it_expires(lease_db):
    c = db.connect(lease_db, None)
    assert db.acquire_lease(c, "outbox", "A", 10, now=100)
    assert not db.acquire_lease(c, "outbox", "B", 10, now=105)        # held
    assert db.acquire_lease(c, "outbox", "A", 10, now=108)            # the holder renews
    assert not db.acquire_lease(c, "outbox", "B", 10, now=112)        # renewed to 118
    assert db.acquire_lease(c, "outbox", "B", 10, now=119)            # expired: B takes over
    assert not db.acquire_lease(c, "outbox", "A", 10, now=120)
    assert db.acquire_lease(c, "webhooks", "A", 10, now=120)          # each name is its own lease
    db.release_lease(c, "outbox", "B")
    assert db.acquire_lease(c, "outbox", "A", 10, now=121)
    c.close()


def test_only_one_of_many_wins_a_race(lease_db):
    wins, barrier = [], threading.Barrier(8)

    def go(i):
        c = db.connect(lease_db, None)
        barrier.wait()
        if db.acquire_lease(c, "race", f"h{i}", 30):
            wins.append(i)
        c.close()

    ts = [threading.Thread(target=go, args=(i,)) for i in range(8)]
    [t.start() for t in ts]
    [t.join() for t in ts]
    assert len(wins) == 1


