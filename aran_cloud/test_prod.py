def test_lastrowid_comes_from_returning_id():
    class Cur:
        description = [type("C", (), {"name": "id"})()]

        def execute(self, sql, params):
            self.sql, self.params = sql, params

        def fetchone(self):
            return db.Row(["id"], (7,))

    class Raw:
        def __init__(self):
            self.cur = Cur()

        def cursor(self, row_factory=None):
            return self.cur

    raw = Raw()
    conn = db.PgConn(raw)
    conn._has_identity_id = lambda t: True
    c = conn.execute("INSERT INTO route_outbox (tenant_id, path) VALUES (?, ?)", ("t1", "/x"))
    assert c.lastrowid == 7
    assert raw.cur.sql.endswith("VALUES (%s, %s) RETURNING id")
    assert raw.cur.params == ("t1", "/x")


