def add_usage(path, tenant_id, period, n):
    lo, hi, _ = prod.period_bounds(period)
    c = sqlite3.connect(path)
    c.execute(
        """WITH RECURSIVE s(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM s WHERE i + 1 < ?)
           INSERT INTO usage_events (tenant_id, at, endpoint, protected_count, latency_ms, status)
           SELECT ?, ? + i * 2.0, '/v1/protect', 1, 1.0, 'ok' FROM s""", (n, tenant_id, lo + 100))
    c.commit()
    c.close()


def prev_period():
    now = time.time()
    lo, _, _ = prod.period_bounds(prod.current_period(now))
    return prod.current_period(lo - 86400)


def test_billing_preview_close_month_and_idempotency(pair):
    a, b, path = pair
    one, two = new_ws(a.url, "Bill One"), new_ws(a.url, "Bill Two")
    period = prev_period()
    c = sqlite3.connect(path)
    c.execute("UPDATE tenants SET plan='growth' WHERE id=?", (one["tenant_id"],))        # Growth: Rs 25,000, 1,000,000 calls, Rs 30 per 1000 over
    c.commit()
    c.close()
    add_usage(path, one["tenant_id"], period, 1_002_500)
    add_usage(path, two["tenant_id"], period, 40)

    r = requests.get(f"{a.url}/v1/billing/preview", params={"period": period}, headers=H(one["admin_key"]), timeout=30)
    assert r.status_code == 200, r.text
    inv = r.json()
    assert inv["period"] == period and inv["currency"] == "INR" and inv["plan"] == "growth" and inv["calls"] == 1_002_500
    lines = {l["code"]: l for l in inv["lines"]}
    assert lines["plan"]["amount_paise"] == 2_500_000                                   # Rs 25,000
    assert lines["included"]["qty"] == 1_000_000
    assert lines["overage"]["qty"] == 2_500 and lines["overage"]["amount_paise"] == 3 * 3000   # 3 started thousands at Rs 30
    assert lines["overage"]["rate_inr_per_million"] == 30_000
    assert inv["total_paise"] == 2_500_000 + 9_000
    assert inv["payment_provider"] is None and "No payment provider" in inv["note"]
    assert inv["closed_invoice_id"] is None
    # the current month so far works too, and a bad period is refused
    assert requests.get(f"{a.url}/v1/billing/preview", headers=H(one["admin_key"]), timeout=30).json()["period"] == prod.current_period()
    assert requests.get(f"{a.url}/v1/billing/preview", params={"period": "2026-13"}, headers=H(one["admin_key"]), timeout=30).status_code == 422
    # scope: a key without the dashboard scope is refused
    narrow = requests.post(f"{a.url}/v1/keys", headers=H(one["admin_key"]), json={"label": "p", "scopes": ["protect"]}, timeout=10).json()["api_key"]
    assert requests.get(f"{a.url}/v1/billing/preview", headers=H(narrow), timeout=30).status_code == 403
    assert requests.get(f"{a.url}/v1/billing/preview", timeout=30).status_code == 401

    # close-month needs the operator token; an API key (even admin) is not enough
    body = {"period": period}
    assert requests.post(f"{a.url}/v1/billing/close-month", headers=H(one["admin_key"]), json=body, timeout=30).status_code in (401, 403)
    assert requests.post(f"{a.url}/v1/billing/close-month", headers={"X-Admin-Token": "wrong"}, json=body, timeout=30).status_code == 401
    assert requests.post(f"{a.url}/v1/billing/close-month", headers={"X-Admin-Token": ADMIN}, json={"period": "2999-01"}, timeout=30).status_code == 422
    assert requests.post(f"{a.url}/v1/billing/close-month", headers={"X-Admin-Token": ADMIN}, json={"period": "nope"}, timeout=30).status_code == 422

    adm = {"X-Admin-Token": ADMIN}
    first = requests.post(f"{a.url}/v1/billing/close-month", headers=adm, json=body, timeout=60)
    assert first.status_code == 200, first.text
    f = first.json()
    mine = {i["tenant_id"]: i for i in f["invoices"]}
    assert mine[one["tenant_id"]]["created"] is True and mine[one["tenant_id"]]["total_paise"] == 2_509_000
    assert mine[two["tenant_id"]]["total_paise"] == 0                                   # Sandbox: free, nothing over
    assert f["created"] >= 2 and "No payment provider" in f["note"]
    inv_id = mine[one["tenant_id"]]["id"]

    # closing again changes nothing, even if usage arrives late and the other instance is asked
    add_usage(path, one["tenant_id"], period, 5_000)
    again = requests.post(f"{b.url}/v1/billing/close-month", headers=adm, json=body, timeout=60).json()
    assert again["created"] == 0 and again["existing"] == f["created"] + f["existing"]
    same = {i["tenant_id"]: i for i in again["invoices"]}[one["tenant_id"]]
    assert same["id"] == inv_id and same["total_paise"] == 2_509_000 and same["created"] is False
    c = sqlite3.connect(path)
    n = c.execute("SELECT COUNT(*) FROM invoices WHERE tenant_id=? AND period=?", (one["tenant_id"], period)).fetchone()[0]
    c.close()
    assert n == 1
    # one tenant only
    solo = requests.post(f"{a.url}/v1/billing/close-month", headers=adm, json={"period": period, "tenant_id": two["tenant_id"]}, timeout=30).json()
    assert solo["created"] == 0 and len(solo["invoices"]) == 1
    assert requests.post(f"{a.url}/v1/billing/close-month", headers=adm, json={"period": period, "tenant_id": "t_nope"}, timeout=30).status_code == 404

    # the tenant sees its own invoices only, and the preview points at the closed one
    mineinv = requests.get(f"{a.url}/v1/billing/invoices", headers=H(one["admin_key"]), timeout=10).json()
    assert [i["id"] for i in mineinv["invoices"]] == [inv_id] and mineinv["payment_provider"] is None
    assert requests.get(f"{a.url}/v1/billing/preview", params={"period": period}, headers=H(one["admin_key"]), timeout=30).json()["closed_invoice_id"] == inv_id
    theirs = requests.get(f"{a.url}/v1/billing/invoices", headers=H(two["admin_key"]), timeout=10).json()
    assert inv_id not in [i["id"] for i in theirs["invoices"]]


