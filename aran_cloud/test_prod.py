# ---------------------------------------------------------------- the adapter's SQL translation (no server)
def tr(sql, pk=("id",)):
    return db.translate(sql, pk_of=lambda t: list(pk))


def test_placeholders_and_percent_signs():
    sql, kind = tr("SELECT * FROM t WHERE a = ? AND b LIKE '<%>%' AND c = ?")
    assert sql == "SELECT * FROM t WHERE a = %s AND b LIKE '<%%>%%' AND c = %s"
    assert kind == ""
    sql, _ = tr("SELECT 'what?' FROM t WHERE x = ?")
    assert sql == "SELECT 'what?' FROM t WHERE x = %s"       # a question mark in a string stays


def test_insert_or_ignore_and_replace():
    sql, _ = tr("INSERT OR IGNORE INTO edges (id, name) VALUES (?, ?)")
    assert sql == "INSERT INTO edges (id, name) VALUES (%s, %s) ON CONFLICT DO NOTHING"
    sql, _ = tr("INSERT OR REPLACE INTO tenant_tokens (token, tenant_id, created_at) VALUES (?, ?, ?)", pk=("tenant_id", "token"))
    assert sql.startswith("INSERT INTO tenant_tokens (token, tenant_id, created_at) VALUES (%s, %s, %s) ON CONFLICT (tenant_id, token) DO UPDATE SET")
    assert sql.endswith("created_at=EXCLUDED.created_at")
    assert "token=EXCLUDED" not in sql                      # key columns are not updated


def test_ddl_autoincrement_real_and_alter():
    sql, _ = tr("CREATE TABLE IF NOT EXISTS x (id INTEGER PRIMARY KEY AUTOINCREMENT, at REAL NOT NULL, name TEXT)")
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "AUTOINCREMENT" not in sql
    assert "at DOUBLE PRECISION NOT NULL" in sql            # a 4 byte REAL would lose a timestamp
    sql, _ = tr("ALTER TABLE routes ADD COLUMN would_block INTEGER NOT NULL DEFAULT 0;")
    assert sql == "ALTER TABLE routes ADD COLUMN IF NOT EXISTS would_block INTEGER NOT NULL DEFAULT 0"


def test_pragma_and_transaction_control():
    assert tr("PRAGMA journal_mode=WAL;") == ("", "skip")           # skipped
    assert tr("PRAGMA table_info(routes);") == ("", "columns:routes")
    sql, kind = tr("BEGIN IMMEDIATE")
    assert "pg_advisory_xact_lock" in sql and kind == "lock"


