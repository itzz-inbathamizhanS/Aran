# ---------------------------------------------------------------- two Cloud instances on one database
class Instance:
    def __init__(self, db_path, trusted, admin=True, sweep=True):
        self.port = free_port()
        self.url = f"http://127.0.0.1:{self.port}"
        env = dict(os.environ, PORT=str(self.port), ARAN_CLOUD_DB=db_path, ARAN_DEMO_MODE="1", ARAN_SIGNUP_LIMIT="1000",
                   ARAN_FAAS_ALLOW_PRIVATE_UPSTREAMS="1", ARAN_TRUSTED_PROXIES=trusted, ARAN_FAAS_TRUST_CLIENT_CERT_HEADER="1",
                   ARAN_FAAS_HOST_SUFFIX="fw.aran.local", ARAN_FAAS_SWEEP_S="1", ARAN_FAAS_LEASE_TTL_S="4", ARAN_ADMIN_TOKEN=ADMIN)
        env.pop("ARAN_CLOUD_DATABASE_URL", None)
        env.update(internal_headers() and {"ARAN_INTERNAL_SECRET": internal_headers()["X-Aran-Internal"]})
        self.proc = subprocess.Popen([sys.executable, "-m", "uvicorn", "main:app", "--port", str(self.port), "--no-proxy-headers"],
                                     cwd=HERE, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        end = time.time() + 40
        while time.time() < end:
            try:
                if requests.get(self.url + "/v1/health", timeout=1).status_code == 200:
                    return
            except requests.RequestException:
                time.sleep(0.3)
        raise RuntimeError("Cloud instance did not start")

    def stop(self):
        self.proc.terminate()
        try:
            self.proc.wait(10)
        except subprocess.TimeoutExpired:
            self.proc.kill()


