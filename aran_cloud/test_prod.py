def test_invoice_numbers_for_a_small_plan(lease_db):
    plans = {"t": {"label": "Test", "monthly_limit": 10, "price_inr": 100, "overage_per_1000_inr": 7}}
    c = db.connect(lease_db, None)
    c.execute("CREATE TABLE usage_events (tenant_id TEXT, at REAL, status TEXT)")
    c.execute("CREATE TABLE route_events (tenant_id TEXT, at REAL, protected_count INTEGER)")
    lo, hi, _ = prod.period_bounds("2026-10")

    def fill(n_calls, n_err=0):
        c.execute("DELETE FROM usage_events")
        c.executemany("INSERT INTO usage_events VALUES ('t1', ?, 'ok')", [(lo + 10 + i,) for i in range(n_calls)])
        c.executemany("INSERT INTO usage_events VALUES ('t1', ?, 'error')", [(lo + 10 + i,) for i in range(n_err)])
        c.executemany("INSERT INTO usage_events VALUES ('t1', ?, 'ok')", [(hi + 5,), (lo - 5,)])     # other months
        c.commit()

    fill(10)
    inv = prod.build_invoice(c, plans, "t", "t1", "2026-10")
    assert inv["total_paise"] == 10000 and inv["calls"] == 10          # exactly the limit: no overage
    fill(11, n_err=5)
    inv = prod.build_invoice(c, plans, "t", "t1", "2026-10")
    assert inv["calls"] == 11                                          # errors and other months are not billed
    assert [l["amount_paise"] for l in inv["lines"]] == [10000, 0, 700, 0]       # 1 started thousand = 7 rupees
    fill(10 + 1000)
    assert prod.build_invoice(c, plans, "t", "t1", "2026-10")["total_paise"] == 10000 + 700
    fill(10 + 1001)
    assert prod.build_invoice(c, plans, "t", "t1", "2026-10")["total_paise"] == 10000 + 1400
    c.execute("INSERT INTO route_events VALUES ('t1', ?, 3)", (lo + 50,))
    c.execute("INSERT INTO route_events VALUES ('t1', ?, 4)", (lo + 60,))
    c.commit()
    routes = prod.build_invoice(c, plans, "t", "t1", "2026-10")["lines"][3]
    assert routes["qty"] == 2 and routes["values_protected"] == 7 and routes["amount_paise"] == 0
    c.close()


