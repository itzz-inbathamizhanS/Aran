@pytest.mark.skipif(not PG_URL or not db.is_postgres(PG_URL), reason="set ARAN_CLOUD_DATABASE_URL to a Postgres URL to run this against a real server")
def test_adapter_on_real_postgres():
    name = f"adapter_t_{random.randint(10**6, 10**7)}"
    c = db.connect("unused", PG_URL)
    try:
        with c:
            c.execute(f"CREATE TABLE {name} (id INTEGER PRIMARY KEY AUTOINCREMENT, k TEXT UNIQUE, at REAL NOT NULL, n INTEGER DEFAULT 0)")
            c.execute(f"CREATE TABLE {name}_kv (k TEXT PRIMARY KEY, v TEXT)")
        with c:
            a = c.execute(f"INSERT INTO {name} (k, at, n) VALUES (?, ?, ?)", ("a", 1793812933.6102498, 5))
            b = c.execute(f"INSERT INTO {name} (k, at, n) VALUES (?, ?, ?)", ("b", 2.5, 7))
        assert b.lastrowid == a.lastrowid + 1
        with c:
            assert c.execute(f"INSERT OR IGNORE INTO {name} (k, at) VALUES (?, ?)", ("a", 1.0)).rowcount == 0
            c.execute(f"INSERT OR REPLACE INTO {name}_kv (k, v) VALUES (?, ?)", ("x", "1"))
            c.execute(f"INSERT OR REPLACE INTO {name}_kv (k, v) VALUES (?, ?)", ("x", "2"))
        assert c.execute(f"SELECT v FROM {name}_kv WHERE k = ?", ("x",)).fetchone()["v"] == "2"
        row = c.execute(f"SELECT at FROM {name} WHERE k = ?", ("a",)).fetchone()
        assert row["at"] == 1793812933.6102498               # full double precision
        s = c.execute(f"SELECT SUM(n) AS s, COUNT(*) AS c FROM {name}").fetchone()
        assert s["s"] == 12 and isinstance(s["s"], int) and s["c"] == 2
        cols = c.execute(f"PRAGMA table_info({name});").fetchall()
        assert [r[1] for r in cols] == ["id", "k", "at", "n"] and cols[0][5] == 1
        assert c.execute("PRAGMA journal_mode=WAL;").fetchall() == []
        with c:
            c.execute(f"ALTER TABLE {name} ADD COLUMN extra TEXT")
            c.execute(f"ALTER TABLE {name} ADD COLUMN extra TEXT")      # a second time is a no-op
        with pytest.raises(db.IntegrityError):
            with c:
                c.execute(f"INSERT INTO {name} (k, at) VALUES (?, ?)", ("a", 1.0))
        d = c.execute(f"SELECT strftime('%Y-%m-%d', at + 19800, 'unixepoch') AS d FROM {name} WHERE k = ?", ("b",)).fetchone()["d"]
        assert d == "1970-01-01"
    finally:
        with c:
            c.execute(f"DROP TABLE IF EXISTS {name}")
            c.execute(f"DROP TABLE IF EXISTS {name}_kv")
        c.close()


